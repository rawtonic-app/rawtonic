//! A scripted camera for tests and for running the app without one
//! (`rawtonic-tether --mock`, its script in `RAWTONIC_TETHER_MOCK` as JSON).
//! It behaves like the cases real bodies show: numbering that restarts,
//! shots fired on the body, a file that arrives late or never, settings
//! fixed on the body, a camera another program holds, an unplugged cable.
use crate::camera::{AbortPoint, Camera, CameraEvent, CameraFile, Driver, Fired};
use crate::protocol::{CameraInfo, CameraStatus, ErrorKind, Setting, TetherError};
use serde::{Deserialize, Serialize};
use std::collections::VecDeque;
use std::time::{Duration, Instant};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct MockSpec {
    pub model: String,
    pub port: String,
    /// Bytes per photo.
    pub file_size: usize,
    pub extension: String,
    /// The camera's file numbers start again after this many shots.
    pub restart_numbering_every: Option<u64>,
    /// From the shutter to the camera reporting the file.
    pub event_delay_ms: u64,
    /// Like cameras whose driver has no separate trigger: firing waits for
    /// the file itself.
    pub no_trigger: bool,
    /// Shots (1-based) whose file never arrives.
    pub lost_shots: Vec<u64>,
    /// Shots (1-based) whose file arrives this much later than usual.
    pub late_shots: Vec<u64>,
    pub late_ms: u64,
    /// Shots fired on the body, this many ms after the camera was opened.
    pub body_shots_ms: Vec<u64>,
    /// Another program holds the camera.
    pub busy: bool,
    /// Listing the cameras takes this long (a driver call that hangs).
    pub list_delay_ms: u64,
    /// The cable comes out after this many downloaded files.
    pub unplug_after: Option<u64>,
    /// The unplug shows only in requests, not in the event poll.
    pub quiet_unplug: bool,
    /// Settings fixed on the body.
    pub read_only: Vec<String>,
    /// The helper stops dead here (crash tests).
    pub abort_mid_download: Option<u64>,
    pub abort_before_event: Option<u64>,
    /// The camera refuses to fire as busy for this long after the connect.
    pub busy_for_ms: u64,
    /// The camera keeps each shot in a USB transfer queue of this many
    /// entries until it is released, and refuses to fire when it is full.
    pub queue_limit: Option<usize>,
    /// Each file is reported a second time right after (as libgphoto2 does
    /// for Fujifilm bodies: object-list polling and the camera's event).
    pub report_twice: bool,
    /// Live view is offered.
    pub preview: bool,
    /// The body's serial number.
    pub serial: Option<String>,
    /// Its firmware version.
    pub firmware: Option<String>,
    /// No memory card in (a camera that then keeps photos in its memory).
    pub no_card: bool,
    /// The card is taken out this long after the connect.
    pub card_out_after_ms: Option<u64>,
    /// Save to cannot be read.
    pub target_read_fails: bool,
    /// Firing drops the reports the camera has made but nobody read yet
    /// (as libgphoto2's Canon EOS trigger clears its collected events).
    pub fire_drops_reports: bool,
    /// Each exposure gives a RAW and a JPEG file (same name, .JPG).
    pub raw_and_jpeg: bool,
    /// The JPEG comes this much after its RAW (else right after it): later
    /// exposures' files can come in between.
    pub jpeg_late_ms: u64,
    /// With `raw_and_jpeg`: JPEGs only from this shot on (the format
    /// changed on the body).
    pub jpeg_from_shot: Option<u64>,
    /// Its "Save to" (capturetarget: sdram or card+sdram), if it has one.
    pub capture_target: Option<String>,
    /// A real photo to hand out (each shot gets its number appended, so no
    /// two are duplicates) instead of generated bytes — for UI checks.
    pub photo: Option<std::path::PathBuf>,
}

